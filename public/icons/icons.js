/**
 * Get an SVG icon by name
 * @param {string} name - Icon name from the Icons object
 * @returns {string} SVG HTML string
 */
function icon(name) {
  return Icons[name] || Icons.file;
}

/**
 * Get file type icon based on MIME type
 * @param {string} mimeType - File MIME type
 * @returns {string} SVG HTML string
 */
function fileTypeIcon(mimeType) {
  if (!mimeType) return Icons.file;

  if (mimeType.startsWith('image/')) return Icons.image;
  if (mimeType.startsWith('video/')) return Icons.video;
  if (mimeType.startsWith('audio/')) return Icons.music;
  if (mimeType.startsWith('text/')) return Icons.fileText;

  if (mimeType.includes('zip') || mimeType.includes('rar') || mimeType.includes('7z') ||
      mimeType.includes('tar') || mimeType.includes('gzip') || mimeType.includes('compressed')) {
    return Icons.archive;
  }

  if (mimeType.includes('javascript') || mimeType.includes('json') || mimeType.includes('xml') ||
      mimeType.includes('html') || mimeType.includes('css') || mimeType.includes('python')) {
    return Icons.code;
  }

  if (mimeType.includes('pdf') || mimeType.includes('document') || mimeType.includes('word') ||
      mimeType.includes('spreadsheet') || mimeType.includes('presentation')) {
    return Icons.fileText;
  }

  return Icons.file;
}
